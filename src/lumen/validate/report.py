"""The validation report, generated from the JSON records of ``lumen validate`` runs (never written by hand).

lumen validate report validation/ --out docs/validation/report.md
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

NOT_VALIDATED = (
    "PMT timing: the shipped PMT values' timing is transcribed but not verified against measurements",
    "times under a fit of the quantum-efficiency shape (the time histogram is weighted at the reference QE)",
    "source-position derivatives near a reflector, behind refracting PMT windows, and at shadow edges",
    "refractive-index derivatives (not available in 0.1)",
)


def _num(v, e=None):
    if v is None:
        return ""
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        return str(v)
    return f"{v:.5g}" + (f" ± {e:.2g}" if isinstance(e, (int, float)) else "")


def _verdict(r):
    v = {True: "pass", False: "**FAIL**", None: "reported"}[r["pass"]]
    return v + (" (provisional)" if r.get("extra", {}).get("provisional") else "")


def _table(rows, cols):
    head = "| " + " | ".join(c for c, _ in cols) + " |\n|" + "---|" * len(cols) + "\n"
    return head + "".join("| " + " | ".join(f(r) for _, f in cols) + " |\n" for r in rows)


def _latest(rows):
    """Keep the newest row of each (check, detector, quantity)."""
    out = {}
    for r in sorted(rows, key=lambda r: r["date"]):
        out[(r["check"], r["detector"], r["quantity"])] = r
    return list(out.values())


def _by_detector(rows):
    out = defaultdict(list)
    for r in rows:
        out[(r["check"], r["detector"])].append(r)
    return out


def markdown(rows) -> str:
    """Return the report's Markdown for record rows."""
    rows = _latest(rows)
    by = defaultdict(list)
    for r in rows:
        by[r["check"]].append(r)
    commits = sorted({tuple(sorted(r["commits"].items())) for r in rows})
    out = ["# lumen validation report", "",
           "Generated by `lumen validate report` from the checks' JSON records; every number below is a record's.", "",
           "Records from: " + "; ".join(", ".join(f"{k} {v}" for k, v in c) for c in commits) + ".", ""]  # fmt: skip
    common = [("value", lambda r: _num(r["value"], r["error"])), ("z", lambda r: _num(r["z"])),
              ("result", _verdict), ("reference", lambda r: str(r["reference"])), ("device", lambda r: r["gpu"]),
              ("date", lambda r: r["date"])]  # fmt: skip
    named = [("detector", lambda r: r["detector"]), ("quantity", lambda r: r["quantity"])]
    sections = (
        ("Charge", "charge", lambda r: r["quantity"] in ("ratio", "truncated photons") or "chi2" in r["quantity"]),
        ("Gradients", "gradients", lambda r: True),
        ("Geometry import", "geometry", lambda r: True),
        ("Overlaps through the step", "overlaps", lambda r: True),
    )
    out += ["## Summary", "", "| check | detector | gated rows passing |", "|---|---|---|"]
    for (c, d), rs in sorted(_by_detector(rows).items()):
        g = [r for r in rs if r["pass"] is not None]
        out.append(f"| {c} | {d} | {sum(bool(r['pass']) for r in g)} of {len(g)} |")
    out.append("")
    for title, check, keep in sections:
        sel = [r for r in by.get(check, []) if keep(r)]
        if not sel:
            continue
        gated = [r for r in sel if r["pass"] is not None]
        out += [f"## {title}", "", f"{sum(bool(r['pass']) for r in gated)} of {len(gated)} gated rows pass.", ""]
        note = [("note", lambda r: str(r.get("extra", {}).get("note", "")))] if check == "gradients" else []
        out += [_table(sorted(sel, key=lambda r: (r["detector"], r["quantity"])), named + common + note), ""]
    out += ["## Not validated", ""] + [f"- {x}" for x in NOT_VALIDATED] + [""]
    return "\n".join(out)


def write(rows, path) -> Path:
    """Write the report for record rows to ``path`` (Markdown); return the path."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(markdown(rows))
    return p
