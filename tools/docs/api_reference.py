"""Write docs/reference/api.md from the docstrings of lumen's public names (the first line of each, and its signature).

    python tools/docs/api_reference.py [--check]        # --check: exit 1 when the page differs from what it writes

tests/unit/test_doc_pages.py runs the check, so the page cannot drift from the code.
"""

from __future__ import annotations

import dataclasses
import importlib
import inspect
import sys
from pathlib import Path

PAGE = Path(__file__).resolve().parents[2] / "docs" / "reference" / "api.md"
INTRO = """# API reference

The public names, each with its signature and the first line of its docstring (`help(...)` gives the rest). This page
is generated by `tools/docs/api_reference.py` from the code; do not edit it by hand. Units are m, ns, nm and eV.
"""
SECTIONS = (
    ("Converting, loading and simulating", "lumen", ("convert", "load", "simulate")),
    ("The detector", "lumen.api.Detector", ("params", "sensor_table", "save_calibration", "with_responses", "digest")),
    ("The light", "lumen", ("Light",)),
    ("Parameters", "lumen.params.Params", ("info", "explain", "set", "scale")),
    (
        "Readout (after tracking)",
        "lumen.readout",
        (
            "pe",
            "pe_error",
            "pe_density",
            "expected_waveform",
            "waveform_nll",
            "expected_hits",
            "hits_nll",
            "sample",
            "time_nodes",
        ),
    ),
    (
        "Sources",
        "lumen.sources",
        ("Point", "CherenkovSegment", "ScintillationPoint", "ScintillationSegment", "Geant4Steps", "FromArrays"),
    ),
    ("Extending lumen", "lumen", ("Param", "source", "response", "medium_model", "surface_model")),
)


def _resolve(path: str):
    mod, _, attr = path.partition(".") if path == "lumen" else path.rpartition(".")
    if path == "lumen":
        return importlib.import_module("lumen")
    try:
        return importlib.import_module(path)
    except ModuleNotFoundError:
        return getattr(importlib.import_module(mod), attr)


def _signature(obj) -> str:
    if inspect.isclass(obj) and dataclasses.is_dataclass(obj):
        fields = [f for f in dataclasses.fields(obj) if f.init]
        return "(" + ", ".join(f.name for f in fields) + ")"
    try:
        return str(inspect.signature(obj))
    except (TypeError, ValueError):
        return "(...)"


def _summary(obj) -> str:
    doc = inspect.getdoc(obj) or ""
    return " ".join(doc.split("\n\n")[0].split())


def page() -> str:
    out = [INTRO]
    for title, where, names in SECTIONS:
        owner = _resolve(where)
        out.append(f"## {title}\n")
        out.append("| Name | Signature | What it does |\n|---|---|---|")
        for n in names:
            obj = getattr(owner, n)
            sig = _signature(obj).replace("|", "\\|")
            out.append(f"| `{where}.{n}` | `{sig}` | {_summary(obj).replace('|', chr(92) + '|')} |")
        out.append("")
    light = _resolve("lumen").Light
    out.append("### `Light` fields\n")
    out.append("| Field | What |\n|---|---|")
    meaning = {"arrivals": "expected photons counted at each sensor, before its sensor model (S,)",
               "arrivals_error": "their Monte Carlo standard error, from the replicas (S,)",
               "mean_arrival_time": "the arrivals-weighted mean arrival time after emission, ns (S,)",
               "histograms": "the modelled group's histograms: wavelength, hit angle, time (None without one)",
               "health": "what happened to the light that was not counted (docs/reference/errors.md, Health)",
               "provenance": "how the result was made: seed, samples, replicas, chunk, backend, detector, wrt",
               "diagnostics": "what the diagnostics passed to simulate recorded (None without)"}  # fmt: skip
    for f in dataclasses.fields(light):
        out.append(f"| `{f.name}` | {meaning[f.name]} |")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    text = page()
    if "--check" in argv:
        if PAGE.read_text() != text:
            print(f"{PAGE} is out of date: run python tools/docs/api_reference.py")
            return 1
        return 0
    PAGE.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
