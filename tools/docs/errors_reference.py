"""Write the generated part of docs/reference/errors.md: every message a raise site in src/lumen builds, with its error.

    python tools/docs/errors_reference.py [--check]     # --check: exit 1 when the page differs from what it writes

The rows above the generated part explain the messages a user meets most, grouped by when; the generated table lists
every raise site of the package, so no message is missing and none goes stale. A message is the raise's string with
each value filled in at run time written ``<name>`` (the expression's last name); a raise that re-raises, or builds
its message elsewhere, is listed as ``(a message built at run time)``. tests/unit/test_doc_pages.py runs the check.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PAGE = ROOT / "docs" / "reference" / "errors.md"
SRC = ROOT / "src" / "lumen"
BEGIN = "<!-- every message: generated by tools/docs/errors_reference.py; do not edit by hand -->"
END = "<!-- end of the generated messages -->"
HEAD = """## Every message

Every message a raise site in lumen builds, with its error and the module that raises it, generated from the code.
`<name>` stands for a value filled in at run time.

| Message | Error | Module |
|---|---|---|"""
DYNAMIC = "(a message built at run time)"


WRAPPERS = ("sorted", "len", "list", "tuple", "set", "repr", "str", "float", "int", "type", "round", "abs")


def _name(node) -> str:
    """Return the placeholder of a formatted value: its expression's last name (``<name>``), inside a builtin's call."""
    while isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in WRAPPERS and node.args:
        node = node.args[0]
    for sub in ast.walk(node):
        if isinstance(sub, ast.Attribute):
            return sub.attr
        if isinstance(sub, ast.Name):
            return sub.id
        if isinstance(sub, ast.Call):
            continue
    return "value"


def _text(node) -> str | None:
    """Return the message template of a string expression (a literal, an f-string, or their + / implicit join)."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        out = []
        for part in node.values:
            out.append(part.value if isinstance(part, ast.Constant) else f"<{_name(part.value)}>")
        return "".join(out)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        a, b = _text(node.left), _text(node.right)
        return None if a is None or b is None else a + b
    return None


def _cell(s: str) -> str:
    """Return a message as a table cell: one line, its pipes and backticks escaped."""
    s = " ".join(s.split()).replace("|", "\\|")
    return f"`{s}`" if "`" not in s else s.replace("`", "'")


def rows() -> list[tuple[str, str, str]]:
    """Return (message, error, module) of every raise site with a constructed error, sorted by module then message."""
    out = set()
    for path in sorted(SRC.rglob("*.py")):
        module = ".".join(path.relative_to(SRC.parent).with_suffix("").parts).removesuffix(".__init__")
        for node in ast.walk(ast.parse(path.read_text())):
            if not isinstance(node, ast.Raise) or not isinstance(node.exc, ast.Call):
                continue
            func = node.exc.func
            error = func.attr if isinstance(func, ast.Attribute) else getattr(func, "id", None)
            if error is None:
                continue
            msg = _text(node.exc.args[0]) if node.exc.args else None
            out.add((DYNAMIC if not msg else msg, error, module))
    return sorted(out, key=lambda r: (r[2], r[0], r[1]))


def page() -> str:
    """Return errors.md with its generated part written from the code."""
    text = PAGE.read_text()
    head = text.split(BEGIN)[0].rstrip("\n")
    table = "\n".join(f"| {_cell(m)} | `{e}` | `{mod}` |" for m, e, mod in rows())
    return f"{head}\n\n{BEGIN}\n{HEAD}\n{table}\n{END}\n"


def main(argv) -> int:
    new = page()
    if "--check" in argv:
        if PAGE.read_text() != new:
            print("docs/reference/errors.md is out of date: run python tools/docs/errors_reference.py")
            return 1
        return 0
    PAGE.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
