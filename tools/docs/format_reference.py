"""Write docs/reference/format.md, the detector file's layout, from the records (lumen.format.schema) and the one
layout rule the writer and reader share (lumen.format.io: FILES, HEAD, field_types).

    python tools/docs/format_reference.py [--check]      # --check: exit 1 when the page differs from what it writes

tests/unit/test_doc_pages.py runs the check, so the page cannot drift from the code.
"""

from __future__ import annotations

import dataclasses
import sys
import typing
from pathlib import Path

from lumen.format import io, schema

PAGE = Path(__file__).resolve().parents[2] / "docs" / "reference" / "format.md"
INTRO = f"""# The detector file

A detector file (`{schema.SCHEMA}`) is a `<name>.lumen/` directory of canonical JSON (sorted
keys, one-space indent, floats as the shortest text that reads back exactly, one record per line) and one float64
`.npy` file per array, each file's digest in the manifest of `detector.json` (an array's: the sha256 of its dtype,
shape and bytes). Beside them: `sensors.json` and `sensors.ids.json` (the sensor set and its id map), and
`calibrations/`. This page is generated by `tools/docs/format_reference.py` from the records (`lumen.format.schema`)
and the layout the writer and reader share (`lumen.format.io`); do not edit it by hand.

The rule:

- a record is a mapping of its fields by name; a field at its default is left out; a record kept in a dict under its
  own name (or a property under its key) does not store that field;
- a list of records at the top level (`placements`, `skins`, `borders`) is a table: one row per record, its fields in
  field order, except that a vector field (`tuple[float, ...]`) is one (n, k) array `arrays/<table>/<field>.npy`;
- an array of one or more dimensions is a file `arrays/<its path of keys>.npy`, and its JSON value that path; a 0-d
  array (a constant) is a JSON number.

The content digest is the sha256 of the manifest of every file but `detector.json`, whose fields are labels.
Values are in m, ns, eV and rad, or in the unit the field's name gives.
"""


def _type(h) -> str:
    s = str(h).replace("typing.", "").replace("lumen.format.schema.", "").replace("numpy.ndarray", "array")
    return s.replace("<class '", "").replace("'>", "").replace("|", "\\|")


def _records() -> list:
    """Return the records reachable from DetectorFile, in the order first met."""
    out, todo = [], [schema.DetectorFile]
    while todo:
        t = todo.pop(0)
        if t in out:
            continue
        out.append(t)
        for h in io.field_types(t).values():
            for a in (h, *typing.get_args(h), *(x for y in typing.get_args(h) for x in typing.get_args(y))):
                if dataclasses.is_dataclass(a) and a not in out:
                    todo.append(a)
    return out


def page() -> str:
    out = [INTRO, "## Files", "", "| File | Fields |", "|---|---|"]
    out.append(f"| `detector.json` | {', '.join(f'`{k}`' for k in io.HEAD)}, `schema`, `manifest` |")
    for f, keys in io.FILES.items():
        out.append(f"| `{f}` | {', '.join(f'`{k}`' for k in keys)} |")
    out += ["", "## Records", ""]
    for t in _records():
        if t is schema.DetectorFile:
            continue
        out += [f"### {t.__name__}", "", "| Field | Type | Default |", "|---|---|---|"]
        for f in dataclasses.fields(t):
            d = f.default_factory() if f.default_factory is not dataclasses.MISSING else f.default
            shown = "" if d is dataclasses.MISSING else f"`{d!r}`"
            out.append(f"| `{f.name}` | `{_type(io.field_types(t)[f.name])}` | {shown} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = page()
    if "--check" in argv:
        if not PAGE.exists() or PAGE.read_text() != text:
            print(f"{PAGE} is out of date: run python tools/docs/format_reference.py")
            return 1
        return 0
    PAGE.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
